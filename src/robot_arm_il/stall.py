"""Why behaviour cloning stops moving: `ra-stall` writes reports/stall.{md,json}.

Two measurements. The copy baseline asks how well "repeat the current joints" predicts the
expert's action h steps ahead, with no learning at all. The stall probe rolls policies out and
records how many episodes end frozen, and where the arm and the cube are when that happens.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import torch

from .config import N_ARM_JOINTS
from .dataset import DemoSet, load_demoset, normalisation_stats, split_episodes
from .env import PickPlaceEnv
from .policy_eval import PolicyRunner

FROZEN_WINDOW = 20  # control steps
FROZEN_RAD = 0.005  # largest joint movement inside the window that still counts as frozen


def copy_baseline(demos: DemoSet, horizons: tuple[int, ...], act_std: np.ndarray) -> dict:
    """Normalised L1 of predicting the arm action h steps ahead with the current joints."""
    out = {}
    for h in horizons:
        errs = []
        for i in range(demos.n_episodes):
            obs, act = demos.episode(i)
            n = len(obs) - h
            if n > 0:
                errs.append(np.abs(act[h:, :N_ARM_JOINTS] - obs[:n, :N_ARM_JOINTS]) / act_std)
        out[str(h)] = float(np.concatenate(errs).mean())
    return out


def is_frozen(joints: np.ndarray, window: int = FROZEN_WINDOW, tol: float = FROZEN_RAD) -> bool:
    """True if every joint stayed within `tol` rad during the last `window` steps."""
    if len(joints) < window:
        return False
    tail = joints[-window:]
    return bool((tail.max(axis=0) - tail.min(axis=0)).max() < tol)


def probe(ckpt: str, episodes: int, seed_start: int, ensemble: float) -> dict:
    env = PickPlaceEnv()
    runner = PolicyRunner(ckpt, torch.device("cpu"), ensemble)
    rows = []
    for seed in range(seed_start, seed_start + episodes):
        obs = env.reset(seed=seed)
        runner.reset()
        joints = []
        while True:
            action = runner.act(obs)
            obs, _, terminated, truncated, info = env.step(action)
            joints.append(obs[:N_ARM_JOINTS].copy())
            if terminated or truncated:
                break
        rows.append(
            {
                "success": bool(info["success"]),
                "frozen": is_frozen(np.array(joints)),
                "command_gap": float(np.abs(action[:N_ARM_JOINTS] - obs[:N_ARM_JOINTS]).max()),
                "cube_z_cm": float(env.cube_pos[2] * 100),
                "cube_goal_cm": float(info["cube_goal_dist"] * 100),
            }
        )
    fails = [r for r in rows if not r["success"]]
    frozen = [r for r in fails if r["frozen"]]

    def med(key: str) -> float | None:
        return float(np.median([r[key] for r in frozen])) if frozen else None

    return {
        "checkpoint": ckpt,
        "ensemble": ensemble,
        "episodes": episodes,
        "failures": len(fails),
        "frozen_failures": len(frozen),
        "frozen_median_cube_goal_cm": med("cube_goal_cm"),
        "frozen_median_cube_z_cm": med("cube_z_cm"),
        "frozen_median_command_gap_rad": med("command_gap"),
    }


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--demos", default="data/demos_clean.npz")
    p.add_argument("--ckpts", nargs="+", required=True, help="name or name:ensemble, in models/")
    p.add_argument("--episodes", type=int, default=100)
    p.add_argument("--seed-start", type=int, default=50_000)
    p.add_argument("--out", default="reports/stall")
    args = p.parse_args(argv)

    demos = load_demoset(args.demos)
    split = split_episodes(demos.n_episodes)
    std = normalisation_stats(demos.subset(split["train"]).actions)["std"][:N_ARM_JOINTS]
    copy = copy_baseline(demos.subset(split["val"]), (0, 1, 5, 10, 19), std)
    probes = {}
    for item in args.ckpts:
        name, _, ens = item.partition(":")
        key = item.replace(":-1000", " (newest chunk)").replace(":0.01", "")
        probes[key] = probe(f"models/{name}.pt", args.episodes, args.seed_start, float(ens or 0.01))
        print(key, json.dumps(probes[key]), flush=True)
    Path(args.out + ".json").write_text(json.dumps({"copy": copy, "probes": probes}, indent=1))

    lines = ["# Stalls", "", "Generated by `ra-stall`.", "", "## Copy baseline", ""]
    lines += ["Normalised L1 of predicting the arm action h steps ahead with the current joints."]
    lines += ["", "| h | " + " | ".join(copy) + " |", "|---|" + "---|" * len(copy)]
    lines += ["| L1 | " + " | ".join(f"{v:.3f}" for v in copy.values()) + " |"]
    lines += ["", "## Rollouts", ""]
    lines += [
        f"Frozen = every joint moved less than {FROZEN_RAD} rad in the last {FROZEN_WINDOW} steps.",
        "Medians are over frozen failures.",
        "",
        "| Run | Failures | Frozen | Cube to goal, cm | Cube height, cm | Command gap, rad |",
        "|---|---|---|---|---|---|",
    ]
    for k, v in probes.items():
        vals = [
            v["frozen_median_cube_goal_cm"],
            v["frozen_median_cube_z_cm"],
            v["frozen_median_command_gap_rad"],
        ]
        cells = " | ".join("–" if x is None else f"{x:.3g}" for x in vals)
        fails = f"{v['failures']}/{v['episodes']}"
        lines.append(f"| {k} | {fails} | {v['frozen_failures']} | {cells} |")
    Path(args.out + ".md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
