"""How much ACT relies on its latent: `ra-latent --ckpts act_clean act_k1 ...`.

Training decodes from a z that has seen the target chunk; inference decodes from z = 0. A large
gap between those two errors means the decoder learned to read the answer out of z.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import torch

from .dataset import load_demoset, split_episodes
from .policies import build_policy
from .train import make_tensors


@torch.no_grad()
def latent_gap(model, obs, actions, mask) -> dict:
    """Masked L1 with z = 0 and with the posterior mean, and the mean KL to the prior."""
    model.eval()
    chunk = model.chunk
    actions, mask = actions[:, :chunk], mask[:, :chunk]
    mu, logvar = model.encode(obs, actions, mask)

    def l1(pred):
        return float(((pred - actions).abs().mean(-1) * mask).sum() / mask.sum())

    kl = (-0.5 * (1 + logvar - mu.pow(2) - logvar.exp())).sum(-1).mean()
    return {"l1_zero": l1(model(obs)), "l1_posterior": l1(model._decode(obs, mu)), "kl": float(kl)}


def probe(path: Path, demos) -> dict:
    ckpt = torch.load(path, map_location="cpu", weights_only=False)
    model = build_policy(ckpt["kind"], **ckpt["kwargs"])
    model.load_state_dict(ckpt["state_dict"])
    stats = {
        k: {a: np.array(v, np.float32) for a, v in s.items()} for k, s in ckpt["stats"].items()
    }
    val = demos.subset(split_episodes(demos.n_episodes)["val"])
    tensors = make_tensors(val, model.chunk, stats, torch.device("cpu"))
    return {"epoch": ckpt["epoch"], "chunk": model.chunk, **latent_gap(model, *tensors)}


def main(argv: list[str] | None = None) -> None:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--ckpts", nargs="+", required=True, help="checkpoint names in --models")
    p.add_argument("--models", default="models")
    p.add_argument("--demos", default="data/demos_clean.npz")
    p.add_argument("--out", default="reports/latent")
    args = p.parse_args(argv)
    demos = load_demoset(args.demos)
    results = {n: probe(Path(args.models) / f"{n}.pt", demos) for n in args.ckpts}
    lines = [
        "# Latent use",
        "",
        "Generated by `ra-latent` on the validation episodes.",
        "",
        "| Run | Chunk | Epoch kept | L1, z = 0 | L1, posterior z | KL |",
        "|---|---|---|---|---|---|",
    ]
    for n, r in results.items():
        lines.append(
            f"| {n} | {r['chunk']} | {r['epoch']} | {r['l1_zero']:.4f} "
            f"| {r['l1_posterior']:.4f} | {r['kl']:.3f} |"
        )
    Path(args.out).with_suffix(".md").write_text("\n".join(lines) + "\n")
    Path(args.out).with_suffix(".json").write_text(json.dumps(results, indent=1))
    print("\n".join(lines[4:]))


if __name__ == "__main__":
    main()
